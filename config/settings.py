"""Django settings for the wine club app.

All deployment-specific configuration comes from environment variables
(see README / deploy/). Without any env vars set, it runs in local dev mode
against a SQLite file.
"""

from pathlib import Path

import environ

BASE_DIR = Path(__file__).resolve().parent.parent

env = environ.Env(
    DEBUG=(bool, False),
    ALLOWED_HOSTS=(list, ["localhost", "127.0.0.1"]),
    CSRF_TRUSTED_ORIGINS=(list, []),
    SECURE_PROXY_SSL=(bool, False),
    TIME_ZONE=(str, "Australia/Adelaide"),
)
