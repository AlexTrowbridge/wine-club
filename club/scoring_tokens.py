"""Short codes that let anyone at an open session score without logging in.

A session gets a code when it opens for scoring and loses it when it leaves the open
state. The code is shown on screen and embedded in a QR code linking to the scoring page.
"""

import re
import secrets
import string

import segno
from django.utils.safestring import mark_safe

TOKEN_LENGTH = 6
TOKEN_ALPHABET = string.digits + string.ascii_uppercase
TOKEN_PATTERN = re.compile(rf"[0-9A-Z]{{{TOKEN_LENGTH}}}")
# Characters people tend to type between groups when copying a code by hand.
TOKEN_SEPARATORS = re.compile(r"[\s-]")

QR_ERROR_LEVEL = "m"
QR_DARK = "#000"
QR_LIGHT = "#fff"
QR_QUIET_ZONE = 2


def generate_token() -> str:
    return "".join(secrets.choice(TOKEN_ALPHABET) for _ in range(TOKEN_LENGTH))


def normalise_token(raw: str) -> str | None:
    """Return the canonical form of a typed code, or None if it can't be a code."""
    token = TOKEN_SEPARATORS.sub("", raw or "").upper()
    return token if TOKEN_PATTERN.fullmatch(token) else None


def qr_svg(url: str) -> str:
    """Inline SVG QR code for ``url``, sized by CSS (it has a viewBox but no width)."""
    qr = segno.make(url, error=QR_ERROR_LEVEL)
    svg = qr.svg_inline(
        dark=QR_DARK, light=QR_LIGHT, border=QR_QUIET_ZONE, omitsize=True, svgclass="qr"
    )
    return mark_safe(svg)  # generated by segno from our own URL, no user markup
